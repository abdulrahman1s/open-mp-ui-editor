#!/usr/bin/env python3
"""Run a real i686 open.mp server in a disposable, loopback-only directory.

Use a TEST-DRIVER binary for callback injection; production binaries omit those natives.
This tests SDK transport, not GTA rendering or real client input.
"""
import argparse
import json
import os
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import tarfile
import tempfile
import urllib.request

ROOT=Path(__file__).resolve().parents[1]
VERSION='v1.5.8.3079'
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--server',type=Path,help='Existing unmodified open.mp distribution (read-only)')
parser.add_argument('--plugin',type=Path,default=ROOT/'build-test/open-mp-ui-editor.so')
parser.add_argument('--includes',type=Path,help='Optional matching omp-stdlib include directory')
args=parser.parse_args()

def command(binary,loader_var):
    loader=os.environ.get(loader_var)
    return ([loader] if loader else [])+[str(binary)]

with tempfile.TemporaryDirectory(prefix='open-mp-ui-integration-') as temporary:
    root=Path(temporary)
    distribution=args.server.resolve() if args.server else root/'distribution/Server'
    if not args.server:
        url=f'https://github.com/openmultiplayer/open.mp/releases/download/{VERSION}/open.mp-linux-x86.tar.gz'
        request=urllib.request.Request(url,headers={'User-Agent':'open-mp-ui-editor-tests'})
        archive=root/'server.tar.gz'
        with urllib.request.urlopen(request,timeout=60) as response,archive.open('wb') as out:
            shutil.copyfileobj(response,out)
        with tarfile.open(archive) as tar:
            tar.extractall(root/'distribution',filter='data')
    work=root/'isolated';work.mkdir()
    shutil.copytree(distribution/'components',work/'components')
    shutil.copy2(args.plugin.resolve(),work/'components/open-mp-ui-editor.so')
    for name in ['gamemodes','scriptfiles/ui','plugins']:(work/name).mkdir(parents=True)
    # Generated by the browser export module, not a separately authored native fixture.
    shutil.copy2(ROOT/'artifacts/exported/Login.json',work/'scriptfiles/ui/login.json')
    (work/'scriptfiles/ui/malformed.json').write_text('{malformed')
    includes=(args.includes or distribution/'qawno/include').resolve()
    compiler=distribution/'qawno/pawncc'
    env=os.environ.copy()
    env['LD_LIBRARY_PATH']=str(distribution/'qawno')+os.pathsep+env.get('LD_LIBRARY_PATH','')
    for source,dest in [(ROOT/'tests/integration.pwn',work/'gamemodes/integration.amx'),(ROOT/'pawn/examples/quickstart.pwn',work/'gamemodes/quickstart.amx')]:
        result=subprocess.run(command(compiler,'PAWN_LOADER')+[str(source),'-i'+str(includes),'-i'+str(ROOT/'pawn/include'),'-o'+str(dest),'-E'],env=env,text=True,capture_output=True)
        if result.returncode:
            raise SystemExit(result.stdout+result.stderr)
    with socket.socket(socket.AF_INET,socket.SOCK_DGRAM) as probe:
        probe.bind(('127.0.0.1',0));port=probe.getsockname()[1]
    config={'announce':False,'name':'open-mp-ui isolated test','max_players':8,'max_bots':2,'network':{'bind':'127.0.0.1','port':port},'rcon':{'password':secrets.token_hex(16)},'pawn':{'main_scripts':['integration'],'legacy_plugins':[]},'logging':{'enable':True,'file':'log.txt','use_timestamp':False}}
    (work/'config.json').write_text(json.dumps(config))
    output=ROOT/'artifacts/integration.log';output.parent.mkdir(exist_ok=True)
    forced=False
    with output.open('w') as stream:
        process=subprocess.Popen(command(distribution/'omp-server','OMP_LOADER'),cwd=work,env=env,stdin=subprocess.PIPE,stdout=stream,stderr=subprocess.STDOUT,text=True)
        try:
            process.wait(timeout=25)
        except subprocess.TimeoutExpired:
            forced=True;process.terminate()
            try:process.wait(timeout=2)
            except subprocess.TimeoutExpired:process.kill();process.wait(timeout=2)
    text=output.read_text(errors='replace')
    if 'UITEST PASS:' not in text or 'UITEST FAIL:' in text or 'Run time error' in text:
        raise SystemExit(text)
    print('Real i686 open.mp: load/show/update/click/cancel/disconnect/unload passed.')
    if forced:print('Gameplay cleanup passed; server process required bounded TERM/KILL fallback.')
